function setupCounters() {
  const counters = $$('[data-count]');
  if (!('IntersectionObserver' in window)) return;
  const observer = new IntersectionObserver(entries => entries.forEach(entry => {
    if (!entry.isIntersecting) return;
    const element = entry.target; observer.unobserve(element);
    const target = Number(element.dataset.count); const suffix = element.dataset.suffix || '';
    const start = performance.now(); const duration = 1100;
    const tick = now => { const p = Math.min((now - start) / duration, 1); const eased = 1 - Math.pow(1-p, 3); element.textContent = `${Math.round(target * eased)}${suffix}`; if (p < 1) requestAnimationFrame(tick); };
    requestAnimationFrame(tick);
  }), { threshold: 0.7 });
  counters.forEach(counter => observer.observe(counter));
}

