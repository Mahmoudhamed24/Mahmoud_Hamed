function isFeaturedRepository(repo) {
  const name = String(repo?.name || '').toLowerCase();
  const fullName = String(repo?.full_name || '').toLowerCase();
  return FEATURED_REPOSITORIES.some(pattern => {
    if (pattern === 'tic' || pattern === 'pww' || pattern === 'templatethree') return name === pattern;
    return name.includes(pattern) || fullName.includes(pattern);
  });
}

function featuredRepositoryRank(repo) {
  const name = String(repo?.name || '').toLowerCase();
  const fullName = String(repo?.full_name || '').toLowerCase();
  const index = FEATURED_REPOSITORIES.findIndex(pattern => {
    if (pattern === 'tic' || pattern === 'pww' || pattern === 'templatethree') return name === pattern;
    return name.includes(pattern) || fullName.includes(pattern);
  });
  return index < 0 ? Number.MAX_SAFE_INTEGER : index;
}

async function fetchUserRepos(username) {
  const collected = [];
  let page = 1;
  while (true) {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 12000);
    let response;
    try {
      response = await fetch(`https://api.github.com/users/${encodeURIComponent(username)}/repos?per_page=100&sort=updated&page=${page}`, {
        headers: { Accept: 'application/vnd.github+json' },
        signal: controller.signal
      });
    } finally {
      clearTimeout(timeoutId);
    }
    if (!response.ok) throw new Error(`GitHub API ${response.status} on page ${page}`);
    const batch = await response.json();
    if (!Array.isArray(batch)) throw new Error('Unexpected GitHub API response');
    collected.push(...batch);
    if (batch.length < 100) break;
    page += 1;
  }
  return collected;
}

function getRepoLanguageList() {
  return [...new Set(publicRepos.map(repo => repo.language).filter(Boolean))].sort((a, b) => a.localeCompare(b));
}

function sortRepositories(repositories, sort) {
  return [...repositories].sort((a, b) => {
    const rankA = featuredRepositoryRank(a);
    const rankB = featuredRepositoryRank(b);
    if (rankA !== rankB) return rankA - rankB; // Featured projects remain first for every sort mode.
    if (sort === 'stars') return (b.stargazers_count || 0) - (a.stargazers_count || 0);
    if (sort === 'name') return String(a.name || '').localeCompare(String(b.name || ''));
    return new Date(b.updated_at || 0) - new Date(a.updated_at || 0);
  });
}

