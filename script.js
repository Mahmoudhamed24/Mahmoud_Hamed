function normalizeUrl(url) {
  if (!url) return '';
  const candidate = /^https?:\/\//i.test(url) ? url : `https://${url}`;
  try { const parsed = new URL(candidate); return ['http:', 'https:'].includes(parsed.protocol) ? parsed.href : ''; }
  catch { return ''; }
}

function getRepoPreviewUrl(repo) {
  // A Homepage URL is the explicit published destination configured by the repository owner.
  const homepage = normalizeUrl(repo.homepage);
  if (homepage) return homepage;

  // For GitHub Pages repositories, generate the conventional Pages URL.
  if (repo.has_pages && repo.owner?.login && repo.name) {
    const owner = repo.owner.login;
    const repository = repo.name;
    const isUserSite = repository.toLowerCase() === `${owner.toLowerCase()}.github.io`;
    return isUserSite
      ? `https://${owner}.github.io/`
      : `https://${owner}.github.io/${encodeURIComponent(repository)}/`;
  }
  return '';
}

function repoImageUrl(repo) {
  return `https://opengraph.githubassets.com/1/${encodeURIComponent(repo.owner.login)}/${encodeURIComponent(repo.name)}`;
}

